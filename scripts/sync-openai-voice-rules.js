#!/usr/bin/env node
'use strict';

const fs = require('fs');
const net = require('net');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'OpenAI_Voice.list');
const sourceUrl = 'https://openai.com/chatgpt-voice.json';
const assert = (condition, message) => { if (!condition) throw new Error(message); };

function parseArgs(args) {
  let check = false;
  let source = null;
  for (let index = 0; index < args.length; index++) {
    if (args[index] === '--check') check = true;
    else if (args[index] === '--source') source = args[++index];
    else throw new Error('unknown argument: ' + args[index]);
  }
  if (args.includes('--source')) assert(source, '--source requires a file path');
  return { check, source };
}

function parsePrefix(value, family) {
  assert(typeof value === 'string', 'source prefix must be a string');
  const match = value.match(/^(.+)\/(\d{1,3})$/);
  assert(match, 'invalid CIDR: ' + value);
  const address = match[1];
  const prefix = Number(match[2]);
  const max = family === 4 ? 32 : 128;
  assert(net.isIP(address) === family, 'CIDR family mismatch: ' + value);
  assert(prefix === max, 'ChatGPT Voice entries must be host routes: ' + value);
  return { type: family === 4 ? 'IP-CIDR' : 'IP-CIDR6', address, cidr: value };
}

function ipv4ToNumber(address) {
  return address.split('.').reduce((value, part) => value * 256 + Number(part), 0);
}

function ipv6ToBigInt(address) {
  let normalized = address;
  if (normalized.includes('.')) {
    const lastColon = normalized.lastIndexOf(':');
    const parts = normalized.slice(lastColon + 1).split('.').map(Number);
    normalized = normalized.slice(0, lastColon + 1)
      + ((parts[0] << 8) | parts[1]).toString(16) + ':'
      + ((parts[2] << 8) | parts[3]).toString(16);
  }
  const halves = normalized.split('::');
  assert(halves.length <= 2, 'invalid IPv6 address: ' + address);
  const left = halves[0] ? halves[0].split(':') : [];
  const right = halves.length === 2 && halves[1] ? halves[1].split(':') : [];
  const missing = 8 - left.length - right.length;
  assert(halves.length === 2 ? missing >= 0 : missing === 0, 'invalid IPv6 address: ' + address);
  const groups = halves.length === 2 ? [...left, ...Array(missing).fill('0'), ...right] : left;
  return groups.reduce((value, group) => (value << 16n) + BigInt(parseInt(group, 16)), 0n);
}

function compareEntries(left, right) {
  if (left.type !== right.type) return left.type.localeCompare(right.type);
  if (left.type === 'IP-CIDR') return ipv4ToNumber(left.address) - ipv4ToNumber(right.address);
  const a = ipv6ToBigInt(left.address);
  const b = ipv6ToBigInt(right.address);
  return a < b ? -1 : a > b ? 1 : 0;
}

function render(data) {
  assert(data && typeof data === 'object' && !Array.isArray(data), 'source JSON must be an object');
  assert(typeof data.creationTime === 'string' && data.creationTime.trim() && !/[\r\n]/.test(data.creationTime), 'source creationTime is invalid');
  assert(Array.isArray(data.prefixes) && data.prefixes.length > 0, 'source prefixes must be a non-empty array');
  const unique = new Map();
  for (const entry of data.prefixes) {
    assert(entry && typeof entry === 'object', 'source prefix entry is invalid');
    const keys = ['ipv4Prefix', 'ipv6Prefix'].filter(key => entry[key] !== undefined);
    assert(keys.length === 1, 'source prefix entry must contain one IP family');
    const parsed = parsePrefix(entry[keys[0]], keys[0] === 'ipv4Prefix' ? 4 : 6);
    unique.set(parsed.type + ',' + parsed.cidr, parsed);
  }
  const entries = [...unique.values()].sort(compareEntries);
  const lines = [
    '# OpenAI ChatGPT Voice IP ranges',
    '# Source: ' + sourceUrl,
    '# Generated by: node scripts/sync-openai-voice-rules.js',
    '# Creation-Time: ' + data.creationTime.trim(),
    '# Prefixes: ' + entries.length,
    ...entries.map(item => `${item.type},${item.cidr},no-resolve`),
    ''
  ];
  return { content: lines.join('\n'), count: entries.length };
}

async function readSource(source) {
  if (source) return fs.readFileSync(path.resolve(source), 'utf8');
  assert(typeof fetch === 'function', 'Node.js 18+ fetch is required when --source is omitted');
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 30000);
  try {
    const response = await fetch(sourceUrl, {
      redirect: 'follow', signal: controller.signal,
      headers: { 'user-agent': 'shadowrocket-rule-openai-voice-sync/1.0' }
    });
    assert(response.ok, 'source request failed: HTTP ' + response.status);
    return await response.text();
  } finally {
    clearTimeout(timeout);
  }
}

async function main() {
  const { check, source } = parseArgs(process.argv.slice(2));
  let data;
  try { data = JSON.parse(await readSource(source)); }
  catch (error) { throw new Error('source is not valid JSON: ' + error.message); }
  const rendered = render(data);
  if (check) {
    assert(fs.existsSync(outputPath), 'OpenAI_Voice.list is missing');
    const current = fs.readFileSync(outputPath, 'utf8').replace(/\r\n/g, '\n');
    const comparable = value => value.replace(/^# Creation-Time: .*$/m, '');
    assert(comparable(current) === comparable(rendered.content), 'OpenAI_Voice.list is stale; run the sync script');
    console.log('PASS: OpenAI_Voice.list is current (' + rendered.count + ' prefixes)');
  } else {
    fs.writeFileSync(outputPath, rendered.content);
    console.log('Synced OpenAI_Voice.list (' + rendered.count + ' prefixes)');
  }
}

main().catch(error => { console.error('FAIL: ' + error.message); process.exit(1); });
